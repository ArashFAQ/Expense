/** صفحه‌ی راهنما: جست‌وجو + بخش‌های جمع‌شونده */
@Composable
fun HelpScreen() {
    var q by rememberSaveable { mutableStateOf("") }
    var open by rememberSaveable { mutableStateOf(-1) }
    val qt = q.trim()
    val list = Help.sections.withIndex().filter { (_, s) ->
        qt.isEmpty() || s.title.contains(qt) || s.keys.contains(qt) || s.body.contains(qt)
    }
    Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
        OutlinedTextField(
            value = q, onValueChange = { q = it }, singleLine = true,
            label = { Text("جست‌وجو در راهنما (مثلا دلار، قسط، دنگ)") }, modifier = Modifier.fillMaxWidth()
        )
        if (list.isEmpty()) Text("چیزی پیدا نشد.", Modifier.padding(8.dp))
        list.forEach { (i, s) ->
            val isOpen = open == i || (qt.isNotEmpty() && list.size == 1)
            Card(onClick = { open = if (open == i) -1 else i }, shape = RoundedCornerShape(18.dp), colors = cardColors()) {
                Column(Modifier.fillMaxWidth().padding(horizontal = 16.dp, vertical = 14.dp)) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Text(s.title, Modifier.weight(1f), fontWeight = FontWeight.Bold, style = MaterialTheme.typography.titleSmall)
                        Text(if (isOpen) "▴" else "▾", color = MaterialTheme.colorScheme.onSurfaceVariant)
                    }
                    AnimatedVisibility(isOpen) {
                        Column(Modifier.padding(top = 8.dp)) { HelpBody(s.body) }
                    }
                }
            }
        }
    }
}

@Composable
private fun HelpBody(body: String) {
    body.lines().forEach { line ->
        val l = line.trim()
        when {
            l.isEmpty() -> Spacer(Modifier.height(4.dp))
            l.startsWith("## ") -> Text(
                l.removePrefix("## "), fontWeight = FontWeight.Bold, color = MaterialTheme.colorScheme.primary,
                modifier = Modifier.padding(top = 10.dp, bottom = 2.dp)
            )
            l.startsWith("• ") -> Row(Modifier.padding(vertical = 2.dp)) {
                Text("•", Modifier.width(14.dp), color = MaterialTheme.colorScheme.primary)
                Text(l.removePrefix("• "), style = MaterialTheme.typography.bodyMedium)
            }
            l.startsWith("مثال:") -> FormBlock(1, "مثال") {
                Text(l.removePrefix("مثال:").trim(), style = MaterialTheme.typography.bodyMedium)
            }
            else -> Text(l, style = MaterialTheme.typography.bodyMedium, modifier = Modifier.padding(vertical = 2.dp))
        }
    }
}
